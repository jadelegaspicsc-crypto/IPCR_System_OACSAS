-- CSC IPCR ONLINE SYSTEM v3
-- Run this entire script in Supabase SQL Editor.
-- Then create the first Auth user from Supabase Dashboard > Authentication > Users.
-- Never expose a service_role/secret key in the website.

create extension if not exists pgcrypto;

do $$ begin
  create type public.user_role as enum ('employee','supervisor','head','admin');
exception when duplicate_object then null;
end $$;

do $$ begin
  create type public.ipcr_status as enum ('draft','for_review','for_approval','approved','returned');
exception when duplicate_object then null;
end $$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text,
  employee_no text,
  position_title text,
  office text default 'OACSAS',
  role public.user_role not null default 'employee',
  supervisor_id uuid references public.profiles(id) on delete set null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ipcrs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  year integer not null,
  period text not null check (period in ('1st Semester','2nd Semester')),
  status public.ipcr_status not null default 'draft',
  total_rating numeric(10,4),
  submitted_at timestamptz,
  reviewed_at timestamptz,
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id,year,period)
);

create table if not exists public.ipcr_items (
  id uuid primary key default gen_random_uuid(),
  ipcr_id uuid not null references public.ipcrs(id) on delete cascade,
  sort_order integer not null default 1,
  function_type text not null check (function_type in ('core','strategic','support')),
  weight numeric(8,4) not null default 0,
  output_outcome text,
  success_indicator text,
  actual_accomplishment text,
  quality numeric(5,2) check (quality is null or (quality >= 1 and quality <= 5)),
  efficiency numeric(5,2) check (efficiency is null or (efficiency >= 1 and efficiency <= 5)),
  timeliness numeric(5,2) check (timeliness is null or (timeliness >= 1 and timeliness <= 5)),
  average_rating numeric(8,4),
  weighted_rating numeric(10,4),
  remarks text,
  created_at timestamptz not null default now()
);

create table if not exists public.ipcr_audit (
  id bigint generated by default as identity primary key,
  ipcr_id uuid references public.ipcrs(id) on delete cascade,
  actor_id uuid references public.profiles(id) on delete set null,
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists profiles_supervisor_idx on public.profiles(supervisor_id);
create index if not exists ipcrs_user_idx on public.ipcrs(user_id);
create index if not exists ipcrs_status_idx on public.ipcrs(status);
create index if not exists ipcr_items_ipcr_idx on public.ipcr_items(ipcr_id);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles(id,email,full_name,role)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data->>'full_name', new.email),
    'employee'
  )
  on conflict (id) do update set email=excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.profiles where id=auth.uid() and role='admin' and active); $$;

create or replace function public.is_supervisor()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.profiles where id=auth.uid() and role in ('supervisor','head','admin') and active); $$;

create or replace function public.can_access_user(target uuid)
returns boolean language sql stable security definer set search_path=public
as $$
  select auth.uid() = target
  or public.is_admin()
  or exists(select 1 from public.profiles p where p.id=target and p.supervisor_id=auth.uid())
  or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='head' and p.office=(select office from public.profiles where id=target));
$$;

alter table public.profiles enable row level security;
alter table public.ipcrs enable row level security;
alter table public.ipcr_items enable row level security;
alter table public.ipcr_audit enable row level security;

drop policy if exists profiles_select on public.profiles;
create policy profiles_select on public.profiles for select using (public.can_access_user(id) or id=auth.uid());

drop policy if exists profiles_update_admin on public.profiles;
create policy profiles_update_admin on public.profiles for update using (public.is_admin()) with check (public.is_admin());

drop policy if exists ipcrs_select on public.ipcrs;
create policy ipcrs_select on public.ipcrs for select using (public.can_access_user(user_id));

drop policy if exists ipcrs_insert on public.ipcrs;
create policy ipcrs_insert on public.ipcrs for insert with check (auth.uid()=user_id);

drop policy if exists ipcrs_update_owner on public.ipcrs;
create policy ipcrs_update_owner on public.ipcrs for update
using (auth.uid()=user_id and status in ('draft','returned'))
with check (auth.uid()=user_id and status in ('draft','for_review','returned'));

drop policy if exists ipcrs_update_reviewer on public.ipcrs;
create policy ipcrs_update_reviewer on public.ipcrs for update
using (public.is_supervisor() and public.can_access_user(user_id))
with check (public.is_supervisor() and public.can_access_user(user_id));

drop policy if exists ipcrs_delete_owner on public.ipcrs;
create policy ipcrs_delete_owner on public.ipcrs for delete
using (auth.uid()=user_id and status='draft');

drop policy if exists items_select on public.ipcr_items;
create policy items_select on public.ipcr_items for select
using (exists(select 1 from public.ipcrs i where i.id=ipcr_id and public.can_access_user(i.user_id)));

drop policy if exists items_insert_owner on public.ipcr_items;
create policy items_insert_owner on public.ipcr_items for insert
with check (exists(select 1 from public.ipcrs i where i.id=ipcr_id and i.user_id=auth.uid() and i.status in ('draft','returned')));

drop policy if exists items_update_owner on public.ipcr_items;
create policy items_update_owner on public.ipcr_items for update
using (exists(select 1 from public.ipcrs i where i.id=ipcr_id and i.user_id=auth.uid() and i.status in ('draft','returned')))
with check (exists(select 1 from public.ipcrs i where i.id=ipcr_id and i.user_id=auth.uid() and i.status in ('draft','returned')));

drop policy if exists items_delete_owner on public.ipcr_items;
create policy items_delete_owner on public.ipcr_items for delete
using (exists(select 1 from public.ipcrs i where i.id=ipcr_id and i.user_id=auth.uid() and i.status in ('draft','returned')));

drop policy if exists items_reviewer on public.ipcr_items;
create policy items_reviewer on public.ipcr_items for all
using (exists(select 1 from public.ipcrs i where i.id=ipcr_id and public.is_supervisor() and public.can_access_user(i.user_id)))
with check (exists(select 1 from public.ipcrs i where i.id=ipcr_id and public.is_supervisor() and public.can_access_user(i.user_id)));

drop policy if exists audit_select on public.ipcr_audit;
create policy audit_select on public.ipcr_audit for select
using (public.is_admin() or actor_id=auth.uid() or exists(select 1 from public.ipcrs i where i.id=ipcr_id and public.can_access_user(i.user_id)));

drop policy if exists audit_insert on public.ipcr_audit;
create policy audit_insert on public.ipcr_audit for insert
with check (auth.uid()=actor_id);

create or replace view public.ipcr_review_queue
with (security_invoker=true)
as
select
  i.id,
  i.user_id,
  p.full_name as employee_name,
  p.email,
  i.year,
  i.period,
  i.status,
  i.total_rating,
  i.created_at,
  i.updated_at
from public.ipcrs i
join public.profiles p on p.id=i.user_id
where i.status in ('for_review','for_approval','returned','approved');

grant select on public.ipcr_review_queue to authenticated;

